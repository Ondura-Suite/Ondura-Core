//! Storage and Microsoft Graph access for Ondura Notizen and Ondura Planer.
//!
//! * Local notebooks and plans are JSON documents in the suite's data
//!   directory (`notes/<id>.json`, `planner/<id>.json`), written atomically.
//! * OneNote and Microsoft Planner are reached through a narrow Graph bridge:
//!   the web code builds the requests, the backend adds the access token of
//!   the chosen account (office or Microsoft 365 mail sign-in) for the
//!   permissions of that area only. Missing consent is reported as
//!   `ONDURA_CONSENT_REQUIRED`; `graph_grant` then asks for it in the browser.

use std::collections::HashMap;
use std::path::PathBuf;
use std::sync::{Arc, Mutex, OnceLock};
use std::time::Duration;

use base64::Engine;
use base64::engine::general_purpose::STANDARD as B64;
use ondura_mail_graph::TokenManager;
use serde::Serialize;
use tauri::AppHandle;
use tauri_plugin_opener::OpenerExt;

type CmdResult<T> = Result<T, String>;

static DATA_DIR: OnceLock<PathBuf> = OnceLock::new();

pub fn init(data_dir: PathBuf) {
    let _ = DATA_DIR.set(data_dir);
}

/// Kinds of local documents.
const KINDS: &[&str] = &["notes", "planner"];

fn kind_dir(kind: &str) -> CmdResult<PathBuf> {
    if !KINDS.contains(&kind) {
        return Err(format!("unknown kind {kind}"));
    }
    let dir = DATA_DIR.get().ok_or("not ready")?.join(kind);
    std::fs::create_dir_all(&dir).map_err(|e| e.to_string())?;
    Ok(dir)
}

/// Ids are generated by the app; anything else could escape the folder.
pub fn valid_id(id: &str) -> bool {
    !id.is_empty() && id.len() <= 80 && id.chars().all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_')
}

fn doc_path(kind: &str, id: &str) -> CmdResult<PathBuf> {
    if !valid_id(id) {
        return Err(format!("invalid id {id}"));
    }
    Ok(kind_dir(kind)?.join(format!("{id}.json")))
}

#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct StoredDoc {
    pub id: String,
    pub name: String,
    /// Milliseconds since the epoch.
    pub modified: u64,
}

#[derive(serde::Deserialize)]
struct Head {
    #[serde(default)]
    name: String,
}

/// Local notebooks or plans, newest first.
#[tauri::command]
pub async fn store_list(kind: String) -> CmdResult<Vec<StoredDoc>> {
    let dir = kind_dir(&kind)?;
    tokio::task::spawn_blocking(move || {
        let mut out = Vec::new();
        for entry in std::fs::read_dir(&dir).map_err(|e| e.to_string())?.flatten() {
            let path = entry.path();
            let Some(id) = path.file_stem().and_then(|s| s.to_str()).filter(|_| path.extension().is_some_and(|e| e == "json")) else { continue };
            if !valid_id(id) {
                continue;
            }
            let modified = entry.metadata().ok().and_then(|m| m.modified().ok()).and_then(|t| t.duration_since(std::time::UNIX_EPOCH).ok()).map(|d| d.as_millis() as u64).unwrap_or(0);
            let name = std::fs::read(&path).ok().and_then(|b| serde_json::from_slice::<Head>(&b).ok()).map(|h| h.name).unwrap_or_default();
            out.push(StoredDoc { id: id.to_string(), name, modified });
        }
        out.sort_by(|a, b| b.modified.cmp(&a.modified));
        Ok(out)
    })
    .await
    .map_err(|e| e.to_string())?
}

#[tauri::command]
pub async fn store_read(kind: String, id: String) -> CmdResult<String> {
    let path = doc_path(&kind, &id)?;
    tokio::fs::read_to_string(&path).await.map_err(|e| e.to_string())
}

/// Writes a document atomically (temporary file, then rename).
#[tauri::command]
pub async fn store_write(kind: String, id: String, json: String) -> CmdResult<()> {
    serde_json::from_str::<serde_json::Value>(&json).map_err(|e| e.to_string())?;
    let path = doc_path(&kind, &id)?;
    let tmp = path.with_extension("json.tmp");
    tokio::fs::write(&tmp, json.as_bytes()).await.map_err(|e| e.to_string())?;
    tokio::fs::rename(&tmp, &path).await.map_err(|e| e.to_string())
}

#[tauri::command]
pub async fn store_delete(kind: String, id: String) -> CmdResult<()> {
    let path = doc_path(&kind, &id)?;
    match tokio::fs::remove_file(&path).await {
        Ok(()) => Ok(()),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(()),
        Err(e) => Err(e.to_string()),
    }
}

// ---------------------------------------------------------------- Graph --

const GRAPH: &str = "https://graph.microsoft.com/v1.0";

/// Permissions per area (never more than the feature needs).
fn area_scope(area: &str) -> CmdResult<&'static str> {
    match area {
        "notes" => Ok("offline_access Notes.ReadWrite"),
        "planner" => Ok("offline_access Tasks.ReadWrite User.ReadBasic.All"),
        _ => Err(format!("unknown area {area}")),
    }
}

/// Only Graph endpoints of the area may be called.
pub fn allowed_path(area: &str, path: &str) -> bool {
    let rel = path.strip_prefix(GRAPH).unwrap_or(path);
    if path.starts_with("http") && !path.starts_with(GRAPH) {
        return false;
    }
    if rel.contains("..") || !rel.starts_with('/') {
        return false;
    }
    match area {
        // OneNote resources come back as absolute URLs below users/sites/groups.
        "notes" => rel.starts_with("/me/onenote/") || (path.starts_with(GRAPH) && rel.contains("/onenote/")),
        "planner" => rel.starts_with("/me/planner/") || rel.starts_with("/planner/") || rel.starts_with("/users/") || rel.starts_with("/users?") || rel == "/me" || rel.starts_with("/me?"),
        _ => false,
    }
}

static TOKENS: OnceLock<Mutex<HashMap<String, Arc<TokenManager>>>> = OnceLock::new();

fn tokens(account: &str) -> CmdResult<Arc<TokenManager>> {
    let map = TOKENS.get_or_init(Default::default);
    if let Some(t) = map.lock().unwrap().get(account) {
        return Ok(Arc::clone(t));
    }
    let (tenant, client_id, secret_key, _, _) = crate::cloud::account_auth(account)?;
    let t = Arc::new(TokenManager::new(ondura_mail_graph::http_client(), tenant, client_id, crate::cloud::secrets()?, secret_key));
    map.lock().unwrap().insert(account.to_string(), Arc::clone(&t));
    Ok(t)
}

#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct GraphResponse {
    pub status: u16,
    pub etag: Option<String>,
    pub content_type: Option<String>,
    /// Text body, or base64 for binary content (images).
    pub body: String,
    pub base64: bool,
}

/// A Graph request of Ondura Notizen (`area = notes`) or Ondura Planer
/// (`area = planner`) with the account's token. Non-2xx answers are
/// returned (not errors) so the app can read Graph's error message.
#[allow(clippy::too_many_arguments)]
#[tauri::command]
pub async fn graph_request(account: String, area: String, method: String, path: String, body: Option<String>, content_type: Option<String>, if_match: Option<String>, binary: Option<bool>) -> CmdResult<GraphResponse> {
    let scope = area_scope(&area)?;
    if !allowed_path(&area, &path) {
        return Err(format!("path not allowed: {path}"));
    }
    let method = reqwest::Method::from_bytes(method.as_bytes()).map_err(|e| e.to_string())?;
    if ![reqwest::Method::GET, reqwest::Method::POST, reqwest::Method::PATCH, reqwest::Method::DELETE].contains(&method) {
        return Err("method not allowed".into());
    }
    let url = if path.starts_with("http") { path.clone() } else { format!("{GRAPH}{path}") };
    let tm = tokens(&account)?;
    let http = ondura_mail_graph::http_client();
    for attempt in 0..4 {
        let token = tm.scoped_token(scope).await.map_err(|e| if ondura_mail_graph::auth::is_consent_error(&e) { "ONDURA_CONSENT_REQUIRED".to_string() } else { e.to_string() })?;
        let mut req = http.request(method.clone(), &url).bearer_auth(token);
        if let Some(b) = &body {
            req = req.header("Content-Type", content_type.as_deref().unwrap_or("application/json")).body(b.clone());
        }
        if let Some(tag) = &if_match {
            req = req.header("If-Match", tag);
        }
        if url.contains("$search=") {
            req = req.header("ConsistencyLevel", "eventual");
        }
        let resp = req.timeout(Duration::from_secs(60)).send().await.map_err(|e| e.to_string())?;
        let status = resp.status();
        if status == reqwest::StatusCode::UNAUTHORIZED && attempt == 0 {
            tm.invalidate().await;
            continue;
        }
        if (status == reqwest::StatusCode::TOO_MANY_REQUESTS || status == reqwest::StatusCode::SERVICE_UNAVAILABLE) && attempt < 3 {
            let wait = resp.headers().get("Retry-After").and_then(|v| v.to_str().ok()).and_then(|v| v.parse().ok()).unwrap_or(2u64);
            tokio::time::sleep(Duration::from_secs(wait.min(30))).await;
            continue;
        }
        let etag = resp.headers().get("ETag").and_then(|v| v.to_str().ok()).map(String::from);
        let ctype = resp.headers().get("Content-Type").and_then(|v| v.to_str().ok()).map(String::from);
        let bytes = resp.bytes().await.map_err(|e| e.to_string())?;
        let binary = binary.unwrap_or(false);
        return Ok(GraphResponse {
            status: status.as_u16(),
            etag,
            content_type: ctype,
            body: if binary { B64.encode(&bytes) } else { String::from_utf8_lossy(&bytes).into_owned() },
            base64: binary,
        });
    }
    Err(ondura_i18n::tr!("Microsoft antwortet nicht. Bitte später erneut versuchen."))
}

/// Asks the user in the browser to allow OneNote or Planner access for an
/// account; the new refresh token replaces the account's old one (consent
/// accumulates, so the account's other features keep working).
#[tauri::command]
pub async fn graph_grant(app: AppHandle, account: String, area: String) -> CmdResult<()> {
    let scope = area_scope(&area)?;
    let (tenant, client_id, secret_key, _personal, email) = crate::cloud::account_auth(&account)?;
    let scopes = format!("openid profile email User.Read {scope}");
    let http = ondura_mail_graph::http_client();
    let opener = app.clone();
    let token = ondura_mail_graph::login_interactive_with_scopes(&http, &tenant, &client_id, &scopes, move |url| opener.opener().open_url(url, None::<&str>).map_err(|e| e.to_string()))
        .await
        .map_err(|e| ondura_i18n::tr!("Microsoft-Anmeldung fehlgeschlagen: {0}", e))?;
    // The consent must come from the same account.
    let me: serde_json::Value = http.get(format!("{GRAPH}/me")).bearer_auth(&token.access_token).send().await.map_err(|e| e.to_string())?.json().await.map_err(|e| e.to_string())?;
    let who = me["mail"].as_str().or(me["userPrincipalName"].as_str()).unwrap_or_default();
    if !who.is_empty() && !who.eq_ignore_ascii_case(&email) {
        return Err(ondura_i18n::tr!("Sie haben sich mit {0} angemeldet, das Konto ist aber {1}.", who, email));
    }
    let tm = TokenManager::new(http, tenant, client_id, crate::cloud::secrets()?, secret_key);
    tm.store(&token).await.map_err(|e| e.to_string())?;
    if let Some(map) = TOKENS.get() {
        map.lock().unwrap().remove(&account);
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn ids_are_checked() {
        assert!(valid_id("nb-1a2b_C"));
        assert!(!valid_id("../secrets"));
        assert!(!valid_id(""));
        assert!(!valid_id("a/b"));
    }

    #[test]
    fn graph_paths_are_limited_per_area() {
        assert!(allowed_path("notes", "/me/onenote/notebooks"));
        assert!(allowed_path("notes", "https://graph.microsoft.com/v1.0/users('x')/onenote/resources/1/$value"));
        assert!(!allowed_path("notes", "/me/messages"));
        assert!(!allowed_path("notes", "https://evil.example/onenote/x"));
        assert!(allowed_path("planner", "/planner/tasks/abc"));
        assert!(allowed_path("planner", "/me/planner/plans"));
        assert!(allowed_path("planner", "/users/123?$select=displayName"));
        assert!(!allowed_path("planner", "/me/onenote/notebooks"));
        assert!(!allowed_path("planner", "/planner/../me/messages"));
    }
}
